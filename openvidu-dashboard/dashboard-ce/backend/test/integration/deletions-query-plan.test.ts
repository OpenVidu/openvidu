import { generate } from '@openvidu-dashboard/data-generator/generator';
import { summarizeExplain } from '@openvidu-dashboard/data-generator/plan';
import { type Db, type Document, MongoClient } from 'mongodb';
import { afterAll, beforeAll, describe, expect, inject, it } from 'vitest';

import { Collection } from '@openvidu-dashboard/typings';

import { type CollectionStep, planSteps } from '../../src/deletions/deletion-plan.js';
import {
	BATCH_SIZE,
	batchQuery,
	keptSetCursor,
	keptSetQueries,
	planContext
} from '../../src/deletions/deletion-runner.js';
import { expectIndexBacked } from '../support/query-plan.js';

/**
 * The batch query of every collection step of a Total deletion, explained on a database generated by the data
 * generator. DELETIONS_PLAN_SCENARIO (S by default) and DELETIONS_PLAN_DAYS (2 by default) set the data; the design
 * figures come from scenario M.
 */

const mongoUri = inject('mongoUri');
const scenario = (process.env.DELETIONS_PLAN_SCENARIO ?? 'S') as 'S' | 'M' | 'L';
const days = Number(process.env.DELETIONS_PLAN_DAYS ?? '2');
const DATABASE = 'dashboard_test_deletions_plan';
const DAY = 86_400_000;
const GENERATION_TIMEOUT_MS = scenario === 'S' ? 600_000 : 3_600_000;

type BatchStep = Extract<CollectionStep, { kind: 'batches' }>;

/** The part of a step's filter its index bounds: the keys a batch scans, kept documents included. */
function indexRange(step: BatchStep): Document {
	switch (step.hint) {
		case 'ts_ttl':
			return { ts: step.filter.ts as Document };
		case 'expiresAt_ttl':
			return { expiresAt: { $type: 'date' } };
		case 'bucket_ttl':
			return { bucket: step.filter.bucket as Document };
		default:
			// The scope index of the daily rollups leads with the scope: its bucket bound filters the keys of every scope.
			return {};
	}
}

describe.skipIf(mongoUri === '')(`deletion batch query plans at scenario ${scenario}`, () => {
	let client: MongoClient;
	let db: Db;
	let steps: BatchStep[];

	beforeAll(async () => {
		client = new MongoClient(mongoUri);
		db = client.db(DATABASE);
		await db.dropDatabase();
		await generate(db, {
			scenario,
			days,
			statsMode: 'track',
			seed: 1,
			retentionDays: { events: 7, stats: 7, tracks: 7, entities: 90 },
			timeseries: true,
			rollups: { fiveMinute: true, nodes: true, roomSums: true },
			mediaNodes: true
		});

		const seen = new Set<string>();

		steps = planSteps('all', false, await planContext(db, new Date())).filter((step): step is BatchStep => {
			const key = `${step.collection} ${JSON.stringify(step.kind === 'batches' ? step.filter : {})}`;
			const fresh = step.kind === 'batches' && !seen.has(key);

			seen.add(key);

			return fresh;
		});
	}, GENERATION_TIMEOUT_MS);

	afterAll(async () => {
		await db.dropDatabase();
		await client.close();
	});

	it('plans every collection step of a Total deletion', () => {
		expect(steps.map((step) => step.collection).sort()).toEqual(
			[
				Collection.EVENTS,
				Collection.TRACK_STATS,
				Collection.TRACK_STATS,
				Collection.TRACK_SUBSCRIPTIONS,
				Collection.TRACKS,
				Collection.INGRESS_SESSIONS,
				Collection.EGRESSES,
				Collection.PARTICIPANTS,
				Collection.INGRESSES,
				Collection.ROOMS,
				Collection.ANALYTICS_5MIN,
				Collection.ANALYTICS_HOURLY,
				Collection.ANALYTICS_DAILY
			].sort()
		);
	});

	it('reads time-series stats through the clustered buckets, without an index hint', async () => {
		const timeseries = steps.filter((step) => step.collection === Collection.TRACK_STATS);
		const buckets = db.collection(`system.buckets.${Collection.TRACK_STATS}`);
		const [info] = await db.listCollections({ name: Collection.TRACK_STATS }, { nameOnly: false }).toArray();
		const options = (info as { options?: { timeseries?: { bucketMaxSpanSeconds?: number } } } | undefined)?.options;
		const maxSpanMs = (options?.timeseries?.bucketMaxSpanSeconds ?? 3_600) * 1_000;

		expect(timeseries).toHaveLength(2);

		for (const step of timeseries) {
			expect(step.byTime).toBe(true);

			// A batch reads the buckets in the order of their start up to the 5,000th deletable measurement, kept rooms'
			// included, plus those that start within a bucket span after it, which the bounded sort needs; the cursor of
			// buckets reads ahead in batches, so up to twice those, and never the rest of the collection. Its delete reads
			// the buckets up to the batch.
			const [bound] = await batchQuery(db, step).toArray();
			const until = (bound?.ts as Date | undefined) ?? (step.filter.ts as { $lt: Date }).$lt;
			const readAhead = await buckets.countDocuments({
				'control.min.ts': { $lte: new Date(until.getTime() + maxSpanMs) }
			});
			const plan = await expectIndexBacked(db, batchQuery(db, step), {
				maxDocsExamined: 2 * readAhead,
				collscanThreshold: 0
			});
			const deletion = summarizeExplain(
				await db.command({
					explain: {
						delete: Collection.TRACK_STATS,
						deletes: [
							{ q: { ...step.filter, ts: { ...(step.filter.ts as Document), $lte: until } }, limit: 0 }
						]
					},
					verbosity: 'executionStats'
				})
			);

			expect(plan.collscan).toBe(false);
			expect(2 * readAhead).toBeLessThan(await buckets.estimatedDocumentCount());
			expect(deletion.collscan).toBe(false);
			expect(deletion.totalDocsExamined ?? Number.POSITIVE_INFINITY).toBeLessThanOrEqual(readAhead);
		}
	});

	it('reads every other batch through its index, examining the batch and the kept documents it meets', async () => {
		for (const step of steps.filter((candidate) => candidate.byTime !== true)) {
			const collection = db.collection(step.collection);
			const [inRange, deletable] = await Promise.all([
				collection.countDocuments(indexRange(step)),
				collection.countDocuments(step.filter)
			]);
			const plan = await expectIndexBacked(db, batchQuery(db, step), {
				maxDocsExamined: Math.min(inRange, BATCH_SIZE + inRange - deletable),
				collscanThreshold: 0
			});

			expect(plan.indexes, step.collection).toEqual([step.hint]);
		}
	});

	it('reads the kept sets through expiresAt_ttl, the end time checked on the grace-window candidates only', async () => {
		// The generated data keeps entities 90 days.
		for (const query of keptSetQueries(new Date(), 90 * DAY)) {
			const candidates = await db
				.collection(query.collection)
				.countDocuments({ expiresAt: query.filter.expiresAt as unknown });
			const plan = await expectIndexBacked(db, keptSetCursor(db, query), {
				maxDocsExamined: candidates,
				collscanThreshold: 0
			});

			expect(plan.indexes, `${query.collection} ${JSON.stringify(query.filter)}`).toEqual(['expiresAt_ttl']);
		}
	});
});
