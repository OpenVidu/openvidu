import { Component } from '@angular/core';
import { TestBed } from '@angular/core/testing';
import { By } from '@angular/platform-browser';
import { MatTooltip } from '@angular/material/tooltip';
import { describe, expect, it } from 'vitest';

import { settle } from '../../../testing/fixtures.js';
import { InfoTip } from './info-tip.js';
import { MediaStatsWarning } from './media-stats-warning.js';

@Component({
	selector: 'ovd-host',
	imports: [InfoTip],
	template: `<div class="header">
			<span>Unique identities</span>
			<ovd-info-tip subject="Unique identities" text="Distinct participant identities." />
		</div>
		<p class="elsewhere">Elsewhere</p>`
})
class Host {}

@Component({
	selector: 'ovd-warning-host',
	imports: [MediaStatsWarning],
	template: `<ovd-media-stats-warning text="Not generated by this server." />`
})
class WarningHost {}

const FREE_TIP =
	'MongoDB reuses this space for new data. The rest of the space the deleted data used stays reserved until the collection is compacted; see Freeing disk space.';

@Component({
	selector: 'ovd-link-host',
	imports: [InfoTip],
	template: `<span>1.8 GB free for new data</span>
		<ovd-info-tip
			subject="free space of Events"
			[text]="text"
			linkText="Freeing disk space"
			href="https://example.org/#freeing-disk-space"
		/>
		<button type="button" class="after">After</button>
		<p class="elsewhere">Elsewhere</p>`
})
class LinkHost {
	protected readonly text = FREE_TIP;
}

function pointer(type: string): Event {
	const event = new MouseEvent('pointerdown', { bubbles: true });

	Object.defineProperty(event, 'pointerType', { value: type });

	return event;
}

async function render() {
	const fixture = TestBed.createComponent(Host);

	await fixture.whenStable();

	const element = fixture.nativeElement as HTMLElement;
	const button = element.querySelector<HTMLButtonElement>('ovd-info-tip button');
	const tooltip = fixture.debugElement.query(By.directive(MatTooltip)).injector.get(MatTooltip);

	return {
		fixture,
		element,
		button,
		tooltip,
		stable: async () => {
			await settle();
			await fixture.whenStable();
		}
	};
}

describe('InfoTip', () => {
	it('is a button named after its subject that shows its text on hover', async () => {
		const { button, stable } = await render();

		expect(button?.getAttribute('aria-label')).toBe('About Unique identities');
		button?.dispatchEvent(new MouseEvent('mouseenter'));
		await stable();
		expect(document.querySelector('.mat-mdc-tooltip')?.textContent.trim()).toBe('Distinct participant identities.');
	});

	it('shows on a mouse click without reaching the element around it', async () => {
		const { element, button, tooltip, stable } = await render();
		let clicks = 0;

		element.querySelector('.header')?.addEventListener('click', () => {
			clicks++;
		});
		button?.dispatchEvent(pointer('mouse'));
		button?.click();
		await stable();

		expect(tooltip._isTooltipVisible()).toBe(true);
		expect(clicks).toBe(0);
	});

	it('toggles on taps and hides on a tap elsewhere', async () => {
		const { element, button, tooltip, stable } = await render();

		button?.dispatchEvent(pointer('touch'));
		button?.click();
		await stable();
		expect(tooltip._isTooltipVisible()).toBe(true);

		button?.dispatchEvent(pointer('touch'));
		button?.click();
		await stable();
		expect(tooltip._isTooltipVisible()).toBe(false);

		button?.dispatchEvent(pointer('touch'));
		button?.click();
		await stable();
		element.querySelector('.elsewhere')?.dispatchEvent(pointer('touch'));
		await stable();
		expect(tooltip._isTooltipVisible()).toBe(false);
	});

	it('names a warning by its text and shows the warning icon', async () => {
		const fixture = TestBed.createComponent(WarningHost);

		await fixture.whenStable();

		const button = (fixture.nativeElement as HTMLElement).querySelector('button');

		expect(button?.getAttribute('aria-label')).toBe('Not generated by this server.');
		expect(button?.classList).toContain('warning');
		expect(button?.querySelector('mat-icon')?.getAttribute('data-mat-icon-name')).toBe('warning');
	});

	describe('with a link', () => {
		async function renderLink() {
			const fixture = TestBed.createComponent(LinkHost);

			await fixture.whenStable();

			const element = fixture.nativeElement as HTMLElement;
			const button = element.querySelector<HTMLButtonElement>('ovd-info-tip button');
			const stable = async () => {
				await settle();
				await fixture.whenStable();
			};

			if (button === null) {
				throw new Error('no icon');
			}

			return { element, button, stable, panel: () => document.querySelector<HTMLElement>('.link-tip') };
		}

		function key(target: Element, name: string, shiftKey = false): KeyboardEvent {
			const event = new KeyboardEvent('keydown', { key: name, shiftKey, bubbles: true, cancelable: true });

			target.dispatchEvent(event);

			return event;
		}

		it('Link tip by keyboard', async () => {
			const { button, stable, panel } = await renderLink();

			expect(button.getAttribute('aria-label')).toBe('About free space of Events');
			expect(button.getAttribute('aria-expanded')).toBe('false');

			// Enter on a focused button activates it.
			button.focus();
			button.click();
			await stable();

			expect(button.getAttribute('aria-expanded')).toBe('true');
			// The link adds a hidden "(opens in a new tab)" for screen readers.
			expect(panel()?.textContent.replace('(opens in a new tab)', '').replace(/\s+/g, ' ').trim()).toBe(FREE_TIP);

			const link = panel()?.querySelector('a');

			expect(link?.textContent).toContain('Freeing disk space');
			expect(link?.getAttribute('href')).toBe('https://example.org/#freeing-disk-space');
			expect(link?.getAttribute('target')).toBe('_blank');

			expect(key(button, 'Tab').defaultPrevented).toBe(true);
			expect(document.activeElement).toBe(link);

			key(link as Element, 'Escape');
			await stable();

			expect(panel()).toBeNull();
			expect(button.getAttribute('aria-expanded')).toBe('false');
			expect(document.activeElement).toBe(button);
			expect(document.querySelector('.mat-mdc-tooltip')).toBeNull();
		});

		it('Link tip by keyboard: Tab leaves the link for what follows the icon, Shift+Tab goes back to it', async () => {
			const { button, stable, panel } = await renderLink();

			button.focus();
			button.click();
			await stable();
			key(button, 'Tab');

			const link = panel()?.querySelector('a') as Element;

			expect(key(link, 'Tab', true).defaultPrevented).toBe(true);
			expect(document.activeElement).toBe(button);
			expect(panel()).not.toBeNull();

			key(button, 'Tab');

			const tab = key(link, 'Tab');

			await stable();
			// The browser then moves focus from the icon to the element after it.
			expect(tab.defaultPrevented).toBe(false);
			expect(document.activeElement).toBe(button);
			expect(panel()).toBeNull();
		});

		it('Link tip by keyboard: a second activation and a click outside close it', async () => {
			const { element, button, stable, panel } = await renderLink();

			button.click();
			await stable();
			expect(panel()).not.toBeNull();
			button.click();
			await stable();
			expect(panel()).toBeNull();

			button.click();
			await stable();

			const elsewhere = element.querySelector<HTMLElement>('.elsewhere');

			elsewhere?.dispatchEvent(pointer('mouse'));
			elsewhere?.click();
			await stable();
			expect(panel()).toBeNull();
			expect(document.activeElement).toBe(button);
		});
	});
});
